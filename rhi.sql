-- Initialize RHI schema (idempotent)
CREATE TABLE IF NOT EXISTS rhi_points (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  rhi_id TEXT NOT NULL,
  period TEXT NOT NULL,
  value REAL NOT NULL,
  UNIQUE(rhi_id, period)
);

-- Seed 2024 months with zeros for six metrics
WITH months(m) AS (
  SELECT '01-2024' UNION ALL SELECT '02-2024' UNION ALL SELECT '03-2024' UNION ALL SELECT '04-2024'
  UNION ALL SELECT '05-2024' UNION ALL SELECT '06-2024' UNION ALL SELECT '07-2024' UNION ALL SELECT '08-2024'
  UNION ALL SELECT '09-2024' UNION ALL SELECT '10-2024' UNION ALL SELECT '11-2024' UNION ALL SELECT '12-2024'
)
INSERT OR REPLACE INTO rhi_points (rhi_id, period, value)
SELECT rid, m, 0.0
FROM months, (SELECT 'rhi96' AS rid UNION ALL SELECT 'rhi97' UNION ALL SELECT 'rhi98' UNION ALL SELECT 'rhi102' UNION ALL SELECT 'rhi103' UNION ALL SELECT 'rhi104');

